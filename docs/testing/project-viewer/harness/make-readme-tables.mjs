// Generates the measurement tables in ../README.md from ../results.json, between the two marker comments. Every number in
// those tables comes from results.json; nothing is typed by hand. results.json is written by collect-results.mjs.
//
//   node make-readme-tables.mjs           rewrite the block in README.md
//   node make-readme-tables.mjs --check   exit 1 if README.md's block differs from what results.json generates
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO } from "./paths.mjs";

const DOCS = join(REPO, "docs", "testing", "project-viewer");
const BEGIN = "<!-- measurements:begin (generated by harness/make-readme-tables.mjs from results.json; do not edit by hand) -->";
const END = "<!-- measurements:end -->";

const n = (v) => (typeof v === "number" ? v.toLocaleString("en-US", { maximumFractionDigits: 3 }) : String(v));
const mb = (bytes) => `${(bytes / 1048576).toFixed(1)} MB`;
const yes = (v) => (v ? "yes" : "no");
const row = (...cells) => `| ${cells.join(" | ")} |`;
const table = (head, rows) => [row(...head), row(...head.map(() => "---")), ...rows.map((r) => row(...r))].join("\n");
const kinds = (obj) => Object.entries(obj ?? {}).map(([k, v]) => `${k} ${v}`).join(", ") || "none";

export function render(r) {
  const out = [];
  const c = r.checks, b = r.bundle, i = r.interaction, f = r.cyclesFacade, a = r.cyclesApp, m = r.memory, l = r.largeScene;
  out.push(`Measured at commit \`${r.commit}\`${r.dirtyOutsideEvidenceFolder ? " **with uncommitted changes outside this folder** (so not yet a statement about a commit)" : " (clean outside this evidence folder, which is committed afterwards)"}, ${r.collectedAt}.`);
  out.push(`Machine: ${r.machine.os}, ${r.machine.browser}, hardware WebGL: ${yes(r.machine.webglHardware)}.`);
  out.push("");
  out.push("**Checks**\n");
  out.push(table(["Check", "Result"], [
    ["`npx tsc --noEmit`", c.tsc.exitCode === 0 ? "0 errors" : `FAILED (exit ${c.tsc.exitCode})`],
    ["`npm run test` (vitest)", `${n(c.vitest.files)} files, ${n(c.vitest.tests)} tests, ${n(c.vitest.passed)} passed, ${n(c.vitest.failed)} failed`],
    ["`npm run build`", c.build.exitCode === 0 ? "passes" : `FAILED (exit ${c.build.exitCode})`],
  ]));
  out.push("\n**Bundle** (gzip at level 9)\n");
  const bundleRows = [
    ["Main chunk", n(b.mainChunk.bytes), n(b.mainChunk.gzip9)],
    ["Lazy 3D view chunk", n(b.lazyViewerChunk.bytes), n(b.lazyViewerChunk.gzip9)],
  ];
  if (b.baseline) {
    bundleRows.push([`Main chunk at \`${b.baseline.commit.slice(0, 12)}\` (baseline)`, n(b.baseline.mainChunk.bytes), n(b.baseline.mainChunk.gzip9)]);
    bundleRows.push(["Main chunk change", n(b.mainChunk.bytes - b.baseline.mainChunk.bytes), n(b.mainChunk.gzip9 - b.baseline.mainChunk.gzip9)]);
  }
  out.push(table(["Chunk", "Bytes", "gzip bytes"], bundleRows));
  out.push("\n**Input on the real viewport** (a fixed list of drags, modifiers, wheel and key presses; see `behave.mjs`)\n");
  const objs = (o) => Object.entries(o ?? {}).map(([id, p]) => `${id} (${p.join(", ")})`).join(", ");
  out.push(table(["Run", "Events seen", "Object centers before", "Object centers after", "Objects stayed put"], [
    ["Inspection (probe tool)", kinds(i.facade.events), objs(i.facade.objectCentersBefore), objs(i.facade.objectCentersAfter), yes(i.facade.objectsDidNotMove)],
    ["Control (the viewport's own default tool)", kinds(i.control.events), objs(i.control.objectCentersBefore), objs(i.control.objectCentersAfter), yes(i.control.objectsDidNotMove)],
  ]));
  out.push(`\nBefore and after screenshots of the inspection run byte-identical: ${yes(i.facade.imagesIdentical)} (adaptive quality and effects settle over time, so pixel equality is not claimed).`);
  out.push("\n**Lifecycle on real WebGL**\n");
  out.push(table(["Measure", "Create and dispose cycles (real adapter)", "Real panel mounts under StrictMode"], [
    ["Cycles planned / completed", `${n(f.plannedCycles)} / ${n(f.cycles)}`, `${n(a.plannedWaitedMounts + a.plannedQuickMounts)} / ${n(a.mountsAndUnmounts)} (${n(a.completedWaitedMounts)} waited for the view, ${n(a.completedQuickMounts)} unmounted while loading)`],
    ["Stuck cycle", "none", a.stuckAtCycle === null || a.stuckAtCycle === undefined ? "none" : `STUCK at ${n(a.stuckAtCycle)}`],
    ["WebGL contexts created", n(f.contextsCreated), n(a.contextsCreatedDuring)],
    ["WebGL contexts still live at the end", n(f.contextsStillLive), n(a.contextsLiveAtEnd)],
    ["Peak canvases in the page at once", n(f.peakConnectedCanvases), "-"],
    ["Canvases connected at the end (before)", n(f.canvasesConnectedAfter), `${n(a.connectedCanvasesAtEnd)} (${n(a.connectedCanvasesBefore)})`],
    ["Live contexts on a detached canvas", n(f.detachedCanvasesWithLiveContext), n(a.liveContextsAttachedToDetachedCanvas)],
    ["Listeners on detached canvases", "-", n(a.listenersOnDetachedCanvases)],
    ["Listeners left", n(f.listenersLeftAfter), `${n(a.listenersOnConnectedTargets)} on connected targets`],
    ["Live resize/intersection observers", n(f.liveObservers), n(a.liveObservers)],
    ["Panel still works afterwards", "-", yes(a.panelStillWorks)],
    ["A click on the model selects its row; Space toggles it", "-", `${yes(a.clickOnModelSelectsRow)}; ${yes(a.spaceTogglesRow)}`],
    ["Seconds for all cycles", "-", n(a.secondsForAllCycles)],
  ]));
  out.push(`\nListeners left on connected targets, by kind: ${kinds(a.listenersByKind)}.`);
  out.push("\n**Memory** (JS heap after forced garbage collection)\n");
  const viewerRows = (m.perViewerCreateDispose ?? []).map((x) => [`Create and dispose, ${x.mode}`, n(x.cycles), `${n(x.bytesPerCycle)} bytes`]);
  const mountRows = (m.perAppMount ?? []).map((x) => [`Mount the panel, WebGL ${x.noWebgl ? "off" : "on"}`, n(x.cycles), `${n(x.bytesPerCycle)} bytes`]);
  out.push(table(["Measure", "Repetitions", "Growth per repetition"], [...viewerRows, ...mountRows]));
  out.push(`\nIn the app: ${mb(m.app.panelShownJsHeapBytes)} with the view shown, ${mb(m.app.afterFiftyCyclesPanelUnmountedJsHeapBytes)} after all mounts with the panel unmounted.`);
  out.push("\n**Large scene** (about 100,000 triangles)\n");
  out.push(table(["Measure", "Value"], [
    ["Seconds from pressing Open to a working view", n(l.secondsUntilViewerWorking)],
    ["JS heap before / after", `${mb(l.jsHeapBeforeBytes)} / ${mb(l.jsHeapAfterBytes)}`],
  ]));
  if (r.realEngine) {
    out.push("\n**Scene client against the real engine** (assertions on the wire; see \"Against the real engine\")\n");
    out.push(table(["Scenario", "Passed"], Object.entries(r.realEngine.scenarios).map(([k, v]) => [`\`${k}\``, yes(v.passed)])));
  }
  out.push("\n**Production build with the app's Content-Security-Policy**\n");
  out.push(table(["Measure", "Value"], [
    ["Production build", yes(r.csp.isProductionBuild)],
    ["Canvases while the view works", n(r.csp.canvasCount)],
    ["Policy violations", r.csp.violations.length ? r.csp.violations.map((v) => `\`${v.replace(/\?.*$/, "")}\``).join("; ") : "none"],
  ]));
  out.push("\n**Original files** hashed before and after every run: " + Object.entries(r.originalFilesUnchanged).map(([k, v]) => `${k} ${v ? "unchanged" : "CHANGED"}`).join(", ") + ".");
  out.push("\n**Screenshots**\n");
  out.push(table(["Screenshot", "Page overflows sideways", "Canvases", "Console errors"], Object.entries(r.screenshots).map(([k, v]) => [`\`${k}\``, yes(v.overflowX), n(v.canvases), v.consoleErrors.length ? v.consoleErrors.map((e) => e.slice(0, 80)).join("; ") : "none"])));
  if (r.harnessErrors?.length) out.push("\n**HARNESS ERRORS (this run is not valid evidence):** " + r.harnessErrors.map((e) => e.split("\n")[0]).join(" | "));
  return out.join("\n");
}

const results = JSON.parse(readFileSync(join(DOCS, "results.json"), "utf8"));
const readme = readFileSync(join(DOCS, "README.md"), "utf8");
const from = readme.indexOf(BEGIN), to = readme.indexOf(END);
if (from < 0 || to < from) throw new Error("README.md has no measurement markers");
const next = `${readme.slice(0, from)}${BEGIN}\n\n${render(results)}\n\n${readme.slice(to)}`;
if (process.argv.includes("--check")) {
  if (next !== readme) { console.error("README.md measurement block is out of date: run node make-readme-tables.mjs"); process.exit(1); }
  console.log("README.md measurement block matches results.json");
} else {
  writeFileSync(join(DOCS, "README.md"), next);
  console.log("README.md measurement block regenerated from results.json");
}
