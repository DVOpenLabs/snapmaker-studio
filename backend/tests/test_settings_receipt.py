"""The settings receipt: what the project asked for, what Studio prepared, what the slice recorded.

Every fixture here is an AUTHORED TEST ARTIFACT: a minimal project archive and a
hand-written G-code config block. None of it was produced by a slicer, and nothing
here was sliced. They exist to put known values on each side of a comparison.
"""
from __future__ import annotations

import zipfile

import pytest

from snapstudio_core import settings_receipt as sr

CONTENT_TYPES = ('<?xml version="1.0"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
                 '<Default Extension="model" ContentType="application/vnd.ms-package.3dmanufacturing-3dmodel+xml"/></Types>')
MODEL = '<?xml version="1.0"?><model unit="millimeter" xmlns="http://schemas.microsoft.com/3dmanufacturing/core/2015/02"><resources/><build/></model>'


def project(tmp_path, name="p.3mf", **settings):
    """An authored project archive carrying only the settings given."""
    import json
    path = tmp_path / name
    with zipfile.ZipFile(path, "w") as z:
        z.writestr("[Content_Types].xml", CONTENT_TYPES)
        z.writestr("3D/3dmodel.model", MODEL)
        z.writestr("Metadata/project_settings.config", json.dumps(settings))
    return str(path)


def gcode(tmp_path, name="s.gcode", **config):
    """An authored G-code file: a header, one move, and a config block of the given values."""
    lines = "".join(f"; {k} = {v}\n" for k, v in config.items())
    path = tmp_path / name
    path.write_text(
        "; HEADER_BLOCK_START\n; generated by Snapmaker Orca 2.3.5 on 2026-08-23 at 10:00:00\n"
        "; total layer number: 6\n; HEADER_BLOCK_END\nPRINT_START\nG1 X10 Y10 E1\nPRINT_END\n\n"
        "; total filament used [g] = 4.00\n; estimated printing time (normal mode) = 41m 12s\n"
        f"; CONFIG_BLOCK_START\n{lines}; CONFIG_BLOCK_END\n", encoding="utf-8")
    return str(path)


def fact(receipt, fact_id):
    return next(f for f in receipt["facts"] if f["id"] == fact_id)


def step(row, a, b):
    return next(s for s in row["steps"] if (s["from"], s["to"]) == (a, b))


ASKED = dict(nozzle_diameter=["0.4", "0.4", "0.4", "0.4"], layer_height="0.20", enable_support="1", enable_prime_tower="1")


def test_the_r2_mismatch_is_surfaced_exactly_without_a_printer(tmp_path):
    original = project(tmp_path, **ASKED)
    sliced = gcode(tmp_path, nozzle_diameter="0.2,0.2,0.2,0.2", layer_height="0.08", enable_support="0", enable_prime_tower="1")
    r = sr.compare(original, None, sliced)
    assert fact(r, "nozzles")["status"] == "changed"
    assert fact(r, "layer_height")["status"] == "changed"
    assert fact(r, "supports")["status"] == "changed"
    assert fact(r, "prime_tower")["status"] == "unchanged"
    s = step(fact(r, "layer_height"), "original", "sliced")
    assert (s["status"], s["from_value"], s["to_value"]) == ("changed", 0.2, 0.08)
    assert "0.2" in s["detail"] and "0.08" in s["detail"]
    assert s["next_action"]


def test_matching_values_are_unchanged_and_say_no_action_is_needed(tmp_path):
    original = project(tmp_path, **ASKED)
    sliced = gcode(tmp_path, nozzle_diameter="0.4,0.4,0.4,0.4", layer_height="0.2", enable_support="1", enable_prime_tower="1")
    r = sr.compare(original, None, sliced)
    assert [f["status"] for f in r["facts"]] == ["unchanged"] * 4
    assert all(s["next_action"] is None for f in r["facts"] for s in f["steps"])


def test_nozzle_order_is_per_tool_and_a_swap_is_a_change(tmp_path):
    original = project(tmp_path, nozzle_diameter=["0.4", "0.6", "0.4", "0.4"])
    sliced = gcode(tmp_path, nozzle_diameter="0.6,0.4,0.4,0.4")
    row = fact(sr.compare(original, None, sliced), "nozzles")
    assert row["status"] == "changed"
    detail = step(row, "original", "sliced")["detail"]
    assert "Tool 1" in detail and "Tool 2" in detail and "Tool 3" not in detail


def test_a_different_number_of_tools_is_a_change(tmp_path):
    original = project(tmp_path, nozzle_diameter=["0.4"] * 4)
    sliced = gcode(tmp_path, nozzle_diameter="0.4,0.4")
    s = step(fact(sr.compare(original, None, gcode_path := sliced), "nozzles"), "original", "sliced")
    assert s["status"] == "changed" and "4" in s["detail"] and "2" in s["detail"]


def test_a_field_the_slice_does_not_record_is_missing_never_off_or_equal(tmp_path):
    original = project(tmp_path, **ASKED)
    sliced = gcode(tmp_path, nozzle_diameter="0.4,0.4,0.4,0.4", layer_height="0.2")   # no enable_support, no tower
    r = sr.compare(original, None, sliced)
    assert fact(r, "supports")["status"] == "missing"
    assert fact(r, "prime_tower")["status"] == "missing"
    s = step(fact(r, "supports"), "original", "sliced")
    assert s["to_value"] is None and "not record" in s["detail"].lower()
    assert s["next_action"]


def test_a_field_the_project_does_not_declare_is_missing_not_off(tmp_path):
    original = project(tmp_path, nozzle_diameter=["0.4"], layer_height="0.2")
    sliced = gcode(tmp_path, nozzle_diameter="0.4", layer_height="0.2", enable_support="0")
    assert fact(sr.compare(original, None, sliced), "supports")["status"] == "missing"


def test_an_unparseable_value_is_missing_not_a_guess(tmp_path):
    original = project(tmp_path, nozzle_diameter=["0.4", "wide"], layer_height="thin", enable_support="maybe")
    sliced = gcode(tmp_path, nozzle_diameter="0.4,0.4", layer_height="0.2", enable_support="1")
    r = sr.compare(original, None, sliced)
    assert [f["status"] for f in r["facts"][:3]] == ["missing", "missing", "missing"]


def test_a_prepared_copy_adds_a_step_and_each_step_is_judged_on_its_own(tmp_path):
    original = project(tmp_path, "o.3mf", **ASKED)
    prepared = project(tmp_path, "p.3mf", **{**ASKED, "layer_height": "0.16"})
    sliced = gcode(tmp_path, nozzle_diameter="0.4,0.4,0.4,0.4", layer_height="0.16", enable_support="1", enable_prime_tower="1")
    row = fact(sr.compare(original, prepared, sliced), "layer_height")
    assert step(row, "original", "prepared")["status"] == "changed"
    assert step(row, "prepared", "sliced")["status"] == "unchanged"
    assert row["status"] == "changed"
    assert "prepared copy" in step(row, "original", "prepared")["detail"].lower()


def test_an_unreadable_prepared_copy_is_not_checked_not_skipped_or_assumed_equal(tmp_path):
    original = project(tmp_path, **ASKED)
    sliced = gcode(tmp_path, nozzle_diameter="0.4,0.4,0.4,0.4", layer_height="0.2", enable_support="1", enable_prime_tower="1")
    r = sr.compare(original, str(tmp_path / "gone.3mf"), sliced)
    row = fact(r, "layer_height")
    assert step(row, "original", "prepared")["status"] == "not_checked"
    assert step(row, "prepared", "sliced")["status"] == "not_checked"
    assert row["status"] == "not_checked"
    assert r["stages"]["prepared"]["state"] == "unreadable"


def test_without_a_slice_nothing_can_be_compared_end_to_end(tmp_path):
    r = sr.compare(project(tmp_path, **ASKED), None, None)
    assert [f["status"] for f in r["facts"]] == ["not_checked"] * 4
    assert r["stages"]["sliced"]["state"] == "not_provided"


def test_an_unreadable_slice_is_not_checked(tmp_path):
    r = sr.compare(project(tmp_path, **ASKED), None, str(tmp_path / "nope.gcode"))
    assert all(f["status"] == "not_checked" for f in r["facts"])
    assert r["stages"]["sliced"]["state"] == "unreadable"


def test_the_scope_is_the_whole_project_and_says_so(tmp_path):
    r = sr.compare(project(tmp_path, **ASKED), None, gcode(tmp_path, nozzle_diameter="0.4"))
    assert r["scope"] == "project"
    assert "plate" in r["scope_note"].lower()


def test_the_prime_tower_is_a_declared_flag_only(tmp_path):
    r = sr.compare(project(tmp_path, **ASKED), None, gcode(tmp_path, nozzle_diameter="0.4", enable_prime_tower="0"))
    row = fact(r, "prime_tower")
    assert row["status"] == "changed"
    text = " ".join(s["detail"] + (s["next_action"] or "") for s in row["steps"]).lower()
    assert "arrange" not in text and "footprint" not in text and "inside the bed" not in text


def test_the_receipt_does_not_speak_for_identity_profile_or_success(tmp_path):
    r = sr.compare(project(tmp_path, **ASKED), None, gcode(tmp_path, nozzle_diameter="0.4,0.4,0.4,0.4"))
    assert "settings only" in r["separate_from"].lower()
    for forbidden in ("will print", "print success", "guarantee"):
        assert forbidden not in str(r).lower()


def test_inputs_are_never_modified(tmp_path):
    import hashlib
    original = project(tmp_path, **ASKED)
    sliced = gcode(tmp_path, nozzle_diameter="0.4")
    digest = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()
    before = (digest(original), digest(sliced))
    sr.compare(original, None, sliced)
    assert (digest(original), digest(sliced)) == before


def test_a_multi_plate_project_says_which_part_it_cannot_resolve(tmp_path):
    import json
    path = tmp_path / "multi.3mf"
