def test_the_http_route_returns_the_receipt_and_refuses_a_request_without_an_original(tmp_path):
    import json
    import threading
    import urllib.error
    import urllib.request

    from snapstudio_api import server

    original = project(tmp_path, **ASKED)
    sliced = gcode(tmp_path, nozzle_diameter="0.2,0.2,0.2,0.2", layer_height="0.08", enable_support="0")
    httpd, token = server.build_server("127.0.0.1", 0)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    try:
        url = f"http://127.0.0.1:{httpd.server_address[1]}/settings_receipt"

        def post(body):
            req = urllib.request.Request(url, data=json.dumps(body).encode(), method="POST",
                                         headers={"Content-Type": "application/json", "X-Auth-Token": token})
            return urllib.request.urlopen(req, timeout=5)

        got = json.loads(post({"original_path": original, "sliced_path": sliced}).read())
        assert fact(got, "layer_height")["status"] == "changed"
        with pytest.raises(urllib.error.HTTPError) as bad:
            post({"sliced_path": sliced})
        assert bad.value.code == 400
    finally:
        httpd.shutdown()
        httpd.server_close()
