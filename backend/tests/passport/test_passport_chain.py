def test_3_recipes_and_mappings_are_retained_or_reported_lost(files):
    recipes = json.loads((FIXTURES / "recipes.json").read_text(encoding="utf-8"))
    mappings = json.loads((FIXTURES / "mappings.json").read_text(encoding="utf-8"))
    result = build_passport(chain_entries(files), recipes=recipes, material_mappings=mappings)
    passport = result.passport
    assert [r.recipe_id for r in passport.recipes] == ["synthetic:mix-a", "synthetic:loops"]
    loops = {r.recipe_id: r for r in passport.recipes}["synthetic:loops"]
    assert loops.execution_supported is False                        # kept, never executable
    assert [m["slot_ref"] for m in passport.material_mappings] == ["slot:0", "project:1:2"]
    assert passport.material_mappings[0]["colour"] == "#FF8800"
    reasons = {(l["kind"], l["id"]): l["reason"] for l in passport.losses}
    assert reasons[("recipe", "synthetic:from-the-future")] == "unknown_schema_version"
    assert reasons[("material_mapping", "project:1:2")] == "field_not_retained:note"
    assert reasons[("material_mapping", "banana")] == "bad_slot_ref"
    assert reasons[("material_mapping", "slot:0")] == "duplicate"
    # the losses survive an export/import round trip and nothing new appears or disappears
    again = decode_passport(json.loads(json.dumps(passport.to_dict()))).value
    assert [r.recipe_id for r in again.recipes] == ["synthetic:mix-a", "synthetic:loops"]
    assert again.material_mappings == passport.material_mappings
    assert sorted(map(json.dumps, again.losses)) == sorted(map(json.dumps, passport.losses))
    assert again.passport_id == passport.passport_id


