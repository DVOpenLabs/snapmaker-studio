def foreign_passport(files, *, claim="local"):
    """A passport as another machine or a hand edit could have made it."""
    doc = build_passport(chain_entries(files)).passport.to_dict()
    for d in doc["derivations"]:
        d["witness"] = claim
        d["declared_by"] = None if claim == "local" else "someone-else"
    for a in doc["artifacts"]:
        a["locator"] = {"path": "/home/someone/secret/original.3mf", "mtime_ns": 1}
    return doc


def test_4_imported_parentage_is_declared_and_a_local_claim_is_downgraded(files):
    result = import_passport(foreign_passport(files))
    assert result["passport"] is not None
    assert {p["witness"] for p in result["parentage"]} == {"declared"}
    assert any(d["code"] == "witness_downgraded" for d in result["diagnostics"])
    assert all(a["locator"] is None for a in result["passport"]["artifacts"])       # a foreign path is dropped
    assert "someone" not in json.dumps(result["passport"])
    assert {p["declared_mismatch"] for p in result["parentage"]} == {None}          # not checked without files


def test_4_a_false_declared_parent_is_flagged_and_never_promoted(files, tmp_path):
    doc = foreign_passport(files, claim="declared")
    other = tmp_path / "elsewhere"
    other.mkdir()
    (other / "original.3mf").write_bytes(b"a different file with the same name")      # exists locally, other sha
    (other / "prepared.3mf").write_bytes(pathlib.Path(files["prepared.3mf"]).read_bytes())
    (other / "sliced.gcode").write_bytes(pathlib.Path(files["sliced.gcode"]).read_bytes())
    result = import_passport(doc, base_dir=str(other))
    by_output = {p["output"]: p for p in result["parentage"]}
    assert by_output["prepared.3mf"]["declared_mismatch"] is True
    assert by_output["sliced.gcode"]["declared_mismatch"] is False
    assert {p["witness"] for p in result["parentage"]} == {"declared"}              # never promoted to local
    assert result["verification"]["summary"]["declared_mismatch"] == ["prepared.3mf"]
    assert result["verification"]["summary"]["all_intact"] is False


def test_4_an_imported_derivation_id_is_never_trusted(files):
    doc = foreign_passport(files, claim="declared")
    doc["derivations"][0]["derivation_id"] = "drv:" + "0" * 40
    imported = decode_passport(doc).value
    assert imported.derivations[0].derivation_id != "drv:" + "0" * 40
    assert imported.derivations[0].derivation_id == Derivation.compute_id(
        imported.derivations[0].output, imported.derivations[0].inputs, imported.derivations[0].producer,
        "declared", "someone-else")


def test_import_never_raises_on_hostile_documents(files):
    base = build_passport(chain_entries(files)).passport.to_dict()
    cases = [None, 5, "not json", "{", [], {}, {"schema_version": "passport/9"}, {"schema_version": "passport/1"},
             {**base, "artifacts": "x"}, {**base, "artifacts": [None, 3, {}]}, {**base, "derivations": [[]]},
             {**base, "artifacts": [base["artifacts"][0]] * 100}]
    for raw in cases:
        result = import_passport(raw)
        assert result["passport"] is None or isinstance(result["passport"], dict)
    assert import_passport({"schema_version": "passport/9"})["passport"] is None
    assert import_passport({**base, "artifacts": [base["artifacts"][0]] * 100})["passport"] is None


def test_a_looping_declared_chain_is_cycle_safe(files):
    doc = foreign_passport(files, claim="declared")
    a, b = doc["artifacts"][0]["artifact_id"], doc["artifacts"][1]["artifact_id"]
    loops = []
    for out, inp in ((a, b), (b, a)):
        loops.append({"schema_version": "derivation/1", "output": out, "inputs": [{"kind": "artifact", "ref": inp}],
                      "producer": {"tool": "x", "version": None}, "witness": "declared", "declared_by": "y"})
    doc["derivations"] = loops
    result = import_passport(doc, base_dir=str(pathlib.Path(files["original.3mf"]).parent))
    assert result["verification"] is not None            # terminated; no hang or recursion error


def test_a_derivation_that_points_outside_the_passport_is_dropped_and_listed(files):
    doc = foreign_passport(files, claim="declared")
    doc["derivations"][0]["inputs"][0]["ref"] = "sha256:" + "a" * 64 + ":1"
    result = import_passport(doc)
    assert ("derivation", "dangling_ref") in {(l["kind"], l["reason"]) for l in result["losses"]}
    assert len(result["parentage"]) == 1
