from __future__ import annotations

import json
import pathlib

import pytest

from snapstudio_core.foundation.artifacts import ByteIdentity, Derivation
from snapstudio_core.passport import build_passport, decode_passport, import_passport, verify_passport

FIXTURES = pathlib.Path(__file__).resolve().parents[1] / "fixtures" / "passport"


@pytest.fixture
def files(tmp_path):
    """Stand-ins for an original, a prepared copy and a sliced output. Not real 3MF or G-code."""
    paths = {}
    for name, body in (("original.3mf", b"synthetic original bytes"), ("prepared.3mf", b"synthetic prepared bytes"),
                       ("sliced.gcode", b"synthetic sliced bytes")):
        p = tmp_path / name
        p.write_bytes(body)
        paths[name] = str(p)
    return paths


def chain_entries(files):
    return [{"path": files["original.3mf"], "role": "original"},
            {"path": files["prepared.3mf"], "role": "prepared", "producer": {"tool": "synthetic-prepare"}},
            {"path": files["sliced.gcode"], "role": "sliced", "producer": {"tool": "synthetic-slicer", "version": "1"}}]


def test_1_manifest_chain_original_prepared_sliced_with_byte_identity(files):
    result = build_passport(chain_entries(files), witness="local")
    passport = result.passport
    assert passport is not None
    roles = {a.role: a for a in passport.artifacts}
    assert set(roles) == {"original", "prepared", "sliced"}
    assert isinstance(roles["original"].bytes, ByteIdentity) and roles["original"].bytes.size_bytes == len(b"synthetic original bytes")
    assert roles["original"].artifact_id.startswith("sha256:")
    by_out = {d.output: d for d in passport.derivations}
    assert [i["ref"] for i in by_out[roles["prepared"].artifact_id].inputs] == [roles["original"].artifact_id]
    assert [i["ref"] for i in by_out[roles["sliced"].artifact_id].inputs] == [roles["prepared"].artifact_id]
    assert all(d.witness == "local" for d in passport.derivations)          # only when a Studio step passes it
    assert all(a.to_dict()["locator"] is None for a in passport.artifacts)
    assert str(files["original.3mf"]) not in json.dumps(passport.to_dict())  # no local path in the document


def test_1_default_build_is_declared_by_the_user_and_generated_role_uses_a_derivation(files, tmp_path):
    generated = tmp_path / "generated.stl"
    generated.write_bytes(b"synthetic generated bytes")
    entries = [{"path": files["original.3mf"], "role": "original"},
               {"path": str(generated), "role": "generated", "parents": [0], "producer": {"tool": "synthetic-generator"}}]
    passport = build_passport(entries).passport
    drv = passport.derivations[0]
    assert (drv.witness, drv.declared_by) == ("declared", "user")
    assert {a.role for a in passport.artifacts} == {"original", "generated"}


def test_1_multi_input_and_identical_bytes_are_handled(files, tmp_path):
    twin = tmp_path / "prepared_twin.3mf"
    twin.write_bytes(pathlib.Path(files["prepared.3mf"]).read_bytes())
    entries = chain_entries(files) + [{"path": str(twin), "role": "prepared", "parents": [0, 1]}]
    result = build_passport(entries)
    assert len(result.passport.artifacts) == 3                      # identical bytes share one artifact
    assert {d.code for d in result.diagnostics} >= {"identical_bytes"}
    multi = build_passport([{"path": files["original.3mf"], "role": "original"},
                            {"path": files["prepared.3mf"], "role": "settings"},
                            {"path": files["sliced.gcode"], "role": "sliced", "parents": [0, 1]}]).passport
    sliced = multi.derivations[-1]
    assert sorted(i["kind"] for i in sliced.inputs) == ["artifact", "settings"]


