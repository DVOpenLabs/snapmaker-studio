def test_2_changed_bytes_invalidate_the_file_and_everything_derived_from_it(files):
    passport = build_passport(chain_entries(files)).passport
    ok = verify_passport(passport, paths={"original.3mf": files["original.3mf"],
                                          "prepared.3mf": files["prepared.3mf"], "sliced.gcode": files["sliced.gcode"]})
    assert ok["summary"]["all_intact"] is True
    pathlib.Path(files["original.3mf"]).write_bytes(b"synthetic original bytes")        # same bytes: still intact
    assert verify_passport(passport, base_dir=str(pathlib.Path(files["original.3mf"]).parent))["summary"]["all_intact"]
    # a same-size replacement is a change
    pathlib.Path(files["original.3mf"]).write_bytes(b"synthetic original BYTES")
    bad = verify_passport(passport, base_dir=str(pathlib.Path(files["original.3mf"]).parent))
    rows = {r["name"]: r for r in bad["artifacts"]}
    assert rows["original.3mf"]["bytes"] == "changed" and rows["original.3mf"]["chain"] == "invalidated"
    assert rows["prepared.3mf"]["bytes"] == "same" and rows["prepared.3mf"]["chain"] == "invalidated"
    assert {"code": "ancestor_changed", "artifact": "original.3mf"} in rows["sliced.gcode"]["reasons"]
    assert bad["summary"]["all_intact"] is False
    status = {d["output"]: d["status"] for d in bad["derivations"]}
    assert status == {"prepared.3mf": "invalidated", "sliced.gcode": "intact"}   # a link is judged on its own bytes


def test_2_missing_or_unlocated_files_are_unverified_never_intact(files):
    passport = build_passport(chain_entries(files)).passport
    nothing = verify_passport(passport)                              # no base_dir, no paths
    assert {r["chain"] for r in nothing["artifacts"]} == {"unverified"}
    assert {r["bytes"] for r in nothing["artifacts"]} == {"unverified"}
    assert nothing["summary"]["all_intact"] is False
    pathlib.Path(files["prepared.3mf"]).unlink()
    gone = verify_passport(passport, base_dir=str(pathlib.Path(files["original.3mf"]).parent))
    rows = {r["name"]: r for r in gone["artifacts"]}
    assert rows["prepared.3mf"]["bytes"] == "missing" and rows["prepared.3mf"]["chain"] == "unverified"
    assert rows["original.3mf"]["chain"] == "intact"
    assert rows["sliced.gcode"]["chain"] == "unverified"             # its parent cannot be checked


