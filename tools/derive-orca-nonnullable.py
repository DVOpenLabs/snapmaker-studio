#!/usr/bin/env python3
"""Derive backend/snapstudio_core/orca_nonnullable.py from Snapmaker Orca's PrintConfig.hpp.

Usage: derive-orca-nonnullable.py PrintConfig.hpp [--write]

Reads the FFF config class blocks (PRINT_CONFIG_CLASS_DEFINE / _DERIVED_DEFINE; every SLA*
class is skipped) and collects the members whose type is a vector that Orca can deserialize
`nil` into only when the option is nullable: Floats, Ints, Percents, FloatsOrPercents, Bools,
EnumsGeneric. Nullable options are created only by `add_nullable()` (the `filament_*`
retraction loop in PrintConfig.cpp) and are not class members, so they are never listed.
The source file is AGPL and is NOT committed; the output is the list of keys only.
"""
from __future__ import annotations

import hashlib
import re
import sys

COMMIT = "b1831e5dcb464172de33783142425aafda834fbc"
VECTOR_TYPES = {"ConfigOptionFloats", "ConfigOptionInts", "ConfigOptionPercents",
                "ConfigOptionFloatsOrPercents", "ConfigOptionBools", "ConfigOptionEnumsGeneric"}
_CLASS = re.compile(r"PRINT_CONFIG_CLASS_(?:DERIVED_)?DEFINE\(\s*(\w+)\s*,")
_MEMBER = re.compile(r"\(\(\s*(ConfigOption\w+)\s*,\s*(\w+)\s*\)\)")


def derive(header_text: str) -> dict[str, tuple[str, str]]:
    starts = [(m.group(1), m.start()) for m in _CLASS.finditer(header_text)
              if m.group(1) != "CLASS_NAME"]          # skip the macro definitions themselves
    found: dict[str, tuple[str, str]] = {}
    for i, (name, pos) in enumerate(starts):
        end = starts[i + 1][1] if i + 1 < len(starts) else len(header_text)
        if name.startswith("SLA"):
            continue
        for typ, key in _MEMBER.findall(header_text[pos:end]):
            if typ in VECTOR_TYPES:
                found[key] = (name, typ)
    return found


def digest(keys) -> str:
    return hashlib.sha256("\n".join(sorted(keys)).encode()).hexdigest()


def render(found: dict) -> str:
    import textwrap
    body = textwrap.fill(", ".join(f'"{k}"' for k in sorted(found)), 88,
                         initial_indent="    ", subsequent_indent="    ")
    return f'''"""Options Snapmaker Orca 2.4.0 declares as non-nullable vectors (GENERATED).

Orca loads a per-part `<metadata key=... value=...>` into the part's config. A vector option
that is not nullable throws "Deserializing nil into a non-nullable object" on a `nil` entry
and the whole project fails to load:
https://github.com/Snapmaker/OrcaSlicer/blob/{COMMIT}/src/libslic3r/Config.hpp#L665-L675

Generated by tools/derive-orca-nonnullable.py from the FFF config class members in
PrintConfig.hpp at Snapmaker/OrcaSlicer {COMMIT} (v2.4.0):
https://github.com/Snapmaker/OrcaSlicer/blob/{COMMIT}/src/libslic3r/PrintConfig.hpp
Class members of type Floats, Ints, Percents, FloatsOrPercents, Bools or EnumsGeneric
(so z_hop_types and retract_lift_enforce are included). SLA classes and options that are not
config class members (clone_objects, position, ...) are not. The only nullable options are
the `filament_<retraction option>` ones made by add_nullable() (PrintConfig.cpp); they are not
class members, so they are not listed and may carry `nil`.
"""
from __future__ import annotations

#: sha256 of the sorted keys joined by newline; pinned by a test against the generator.
SOURCE_DIGEST = "{digest(found)}"

NON_NULLABLE_VECTORS = frozenset({{
{body}
}})
'''


if __name__ == "__main__":
    text = open(sys.argv[1], encoding="utf-8").read()
    found = derive(text)
    out = render(found)
    if "--write" in sys.argv:
        with open("backend/snapstudio_core/orca_nonnullable.py", "w", encoding="utf-8", newline="\n") as f:
            f.write(out)
    print(len(found), digest(found))
